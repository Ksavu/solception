use anchor_lang::prelude::*;

pub const PLATFORM_SEED: &[u8] = b"platform";
pub const LAUNCHPAD_SEED: &[u8] = b"launchpad";
pub const CURVE_SEED: &[u8] = b"curve";

pub const TOKEN_DECIMALS: u8 = 6;
pub const MAX_LAUNCHPAD_NAME_LEN: usize = 32;
pub const MAX_URI_LEN: usize = 200;
/// Hard ceiling on any trade fee, regardless of config: 10%.
pub const ABSOLUTE_MAX_TRADE_FEE_BPS: u16 = 1_000;

/// Layer 0 — the Solception platform itself (singleton).
#[account]
#[derive(InitSpace)]
pub struct Platform {
    pub authority: Pubkey,
    /// Receives launchpad creation fees and claimed platform trade/launch fees.
    pub treasury: Pubkey,
    /// Wallet allowed to pull graduated liquidity to seed the DEX pool.
    pub migration_authority: Pubkey,
    /// Lamports paid to the treasury to create a launchpad.
    pub launchpad_creation_fee: u64,
    /// Platform's cut of every fee generated by every launchpad.
    pub platform_fee_share_bps: u16,
    /// Max trade fee a launchpad may charge.
    pub max_trade_fee_bps: u16,
    pub launchpad_count: u64,
    pub paused: bool,
    pub bump: u8,
}

/// Curve economics a launchpad applies to every token it launches.
#[derive(AnchorSerialize, AnchorDeserialize, Clone, Copy, Debug, InitSpace)]
pub struct CurveConfig {
    /// Starting virtual SOL reserve (lamports).
    pub initial_virtual_sol: u64,
    /// Starting virtual token reserve (base units).
    pub initial_virtual_tokens: u64,
    /// Tokens sold through the curve. Curve completes when all are sold.
    pub curve_token_supply: u64,
    /// Tokens held back to pair with raised SOL on the DEX after graduation.
    pub lp_token_reserve: u64,
}

/// Layer 1 — a launchpad created through Solception.
#[account]
#[derive(InitSpace)]
pub struct Launchpad {
    pub id: u64,
    pub owner: Pubkey,
    /// Where the launchpad's share of fees is claimed to.
    pub fee_recipient: Pubkey,
    #[max_len(MAX_LAUNCHPAD_NAME_LEN)]
    pub name: String,
    /// Off-chain branding JSON (logo, colors, domain, socials).
    #[max_len(MAX_URI_LEN)]
    pub uri: String,
    /// Total fee on each buy/sell.
    pub trade_fee_bps: u16,
    /// Share of the post-platform fee that goes to the token creator.
    pub creator_fee_share_bps: u16,
    /// Lamports charged to launch a token on this pad.
    pub token_launch_fee: u64,
    pub curve: CurveConfig,
    pub token_count: u64,
    pub paused: bool,
    pub created_at: i64,
    pub bump: u8,
}

/// Layer 2 — a token's bonding curve. Holds the raised SOL and accrued fees.
#[account]
#[derive(InitSpace)]
pub struct BondingCurve {
    pub launchpad: Pubkey,
    pub mint: Pubkey,
    pub creator: Pubkey,
    pub virtual_sol_reserves: u64,
    pub virtual_token_reserves: u64,
    pub real_sol_reserves: u64,
    pub real_token_reserves: u64,
    pub lp_token_reserve: u64,
    pub token_total_supply: u64,
    /// Fees are accrued here per trade (no global write-lock), then claimed.
    pub platform_fees_accrued: u64,
    pub launchpad_fees_accrued: u64,
    pub creator_fees_accrued: u64,
    pub complete: bool,
    pub migrated: bool,
    pub created_at: i64,
    pub bump: u8,
}

impl BondingCurve {
    pub fn total_fees_accrued(&self) -> u64 {
        self.platform_fees_accrued + self.launchpad_fees_accrued + self.creator_fees_accrued
    }
}

#[derive(AnchorSerialize, AnchorDeserialize, Clone, Copy, PartialEq, Eq, Debug)]
pub enum FeeBucket {
    Platform,
    Launchpad,
    Creator,
}
